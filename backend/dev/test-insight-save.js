require('dotenv').config();
const mongoose = require('mongoose');
const { saveInsight } = require('../services/insightService');

async function run() {
  const uri = process.env.MONGO_URI;
  if (!uri) {
    throw new Error('Missing MONGO_URI in environment');
  }

  await mongoose.connect(uri);
  console.log('[test-insight-save] Connected to MongoDB');

  const userId = process.argv[2] || process.env.TEST_USER_ID || 'sample-user-1';

  const sampleInsight = {
    userId,
    overview: 'Sample overview generated by test-insight-save',
    overspendAreas: [
      { category: 'Food', amount: 150, why: 'Frequent ordering' },
      { category: 'Transport', amount: 80, why: 'Daily cab rides' },
    ],
    savingsPlan: 'Cut down on outside food to save ₹500 monthly.',
    microTip: 'Carry homemade snacks to avoid impulse buys.',
    prediction: 'risk: moderate overspend',
    raw: { source: 'test-insight-save' },
  };

  const created = await saveInsight(sampleInsight);
  console.log('[test-insight-save] Created Insight ID:', created._id?.toString());
}

run()
  .catch((err) => {
    console.error('[test-insight-save] Error:', err);
    process.exitCode = 1;
  })
  .finally(async () => {
    await mongoose.connection.close();
    console.log('[test-insight-save] Connection closed');
  });


